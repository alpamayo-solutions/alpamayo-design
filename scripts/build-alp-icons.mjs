#!/usr/bin/env node
// Builds the Alpamayo icon sprites and the TypeScript id list from assets/icons/alp/.
//
// assets/icons/alp/detail/<id>.svg  240 grid. assets/icons/alp/small/<id>.svg  24 grid.
// Drawings hold geometry and `class` only. Classes: none = ink line, k = ink fill,
// a = accent line, af = accent fill. A third-party logo that may not be redrawn is one <image> of
// the unaltered file in public/icons/logos/, contained in the square.
//
// Output: public/icons/alp-detail.svg, public/icons/alp-small.svg, composables/alpIconIds.ts
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const source = join(root, 'assets/icons/alp');
const ACCENT = 'var(--icon-accent, currentColor)';
const STYLES = {
    k: 'fill:currentColor;stroke:none',
    a: `stroke:${ACCENT}`,
    af: `fill:${ACCENT};stroke:none`
};
const VARIANTS = { detail: 240, small: 24 };
// `alp_<id>` must fit the /^[a-z0-9_]{1,64}$/ that PREKIT's server applies to icon strings, and
// `-` must be the only separator so that the string form maps back to exactly one id.
const ID = /^[a-z0-9]+(-[a-z0-9]+)*$/;
const MAX_ID_LENGTH = 60;

const TAG = /<(\/?)([a-z]+)((?:\s+[a-zA-Z0-9-]+="[^"]*")*)\s*(\/?)>/y;
const ATTRIBUTE = /([a-zA-Z0-9-]+)="([^"]*)"/g;

/** One drawing's shapes as sprite markup: `class` resolved to a style, everything else kept. */
function shapes(file, viewBox) {
    const text = readFileSync(file, 'utf8');
    const output = [];
    const open = [];
    TAG.lastIndex = 0;
    while (true) {
        const start = TAG.lastIndex + /^\s*/.exec(text.slice(TAG.lastIndex))[0].length;
        if (start === text.length) break;
        TAG.lastIndex = start;
        const match = TAG.exec(text);
        if (!match) throw new Error(`${file}: cannot parse at offset ${start}`);
        const [, closing, tag, attributes, selfClosing] = match;
        if (closing) {
            if (open.pop() !== tag) throw new Error(`${file}: unbalanced </${tag}>`);
            if (tag !== 'svg') output.push(`</${tag}>`);
            continue;
        }
        const parsed = Object.fromEntries([...attributes.matchAll(ATTRIBUTE)].map((m) => [m[1], m[2]]));
        if (tag === 'svg') {
            if (open.length || parsed.viewBox !== `0 0 ${viewBox} ${viewBox}`) {
                throw new Error(`${file}: expected one root <svg> with a ${viewBox} grid`);
            }
            open.push(tag);
            continue;
        }
        const { class: name, ...kept } = parsed;
        if (name !== undefined && !(name in STYLES)) throw new Error(`${file}: bad class ${name}`);
        if ('style' in kept) throw new Error(`${file}: drawings must not set style`);
        if (name) kept.style = STYLES[name];
        const rendered = Object.entries(kept).map(([key, value]) => ` ${key}="${value}"`);
        output.push(`<${tag}${rendered.join('')}${selfClosing ? '/' : ''}>`);
        if (!selfClosing) open.push(tag);
    }
    if (open.length) throw new Error(`${file}: unclosed <${open.pop()}>`);
    return output.join('');
}

function sprite(ids, variant, grid) {
    const symbols = ids.map(
        (id) =>
            `<symbol id="${id}" viewBox="0 0 ${grid} ${grid}">${shapes(join(source, variant, `${id}.svg`), grid)}</symbol>`
    );
    return `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;
}

function idList(ids) {
    const lines = ids.map((id) => `    '${id}'`).join(',\n');
    return `// Generated by scripts/build-alp-icons.mjs from assets/icons/alp. Do not edit.
export const ALP_ICON_IDS = [
${lines}
] as const;

export type AlpIconId = (typeof ALP_ICON_IDS)[number];
`;
}

/** Every generated file, by repo-relative path. Writes nothing. */
export function renderAlpIcons() {
    const manifest = JSON.parse(readFileSync(join(source, 'manifest.json'), 'utf8'));
    const ids = Object.keys(manifest).sort();
    for (const id of ids) {
        if (!ID.test(id) || id.length > MAX_ID_LENGTH) throw new Error(`invalid icon id: ${id}`);
    }
    for (const variant of Object.keys(VARIANTS)) {
        const drawn = readdirSync(join(source, variant)).map((file) => file.replace(/\.svg$/, ''));
        const unlisted = drawn.filter((id) => !(id in manifest));
        const undrawn = ids.filter((id) => !drawn.includes(id));
        if (unlisted.length || undrawn.length) {
            throw new Error(`${variant}: not in manifest [${unlisted}], no drawing [${undrawn}]`);
        }
    }
    return {
        'public/icons/alp-detail.svg': sprite(ids, 'detail', VARIANTS.detail),
        'public/icons/alp-small.svg': sprite(ids, 'small', VARIANTS.small),
        'composables/alpIconIds.ts': idList(ids)
    };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    const files = Object.entries(renderAlpIcons());
    for (const [path, content] of files) {
        mkdirSync(dirname(join(root, path)), { recursive: true });
        writeFileSync(join(root, path), content);
    }
    console.log(`Wrote ${files.map(([path]) => path).join(', ')}`);
}
